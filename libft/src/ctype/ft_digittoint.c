#include "libft.h"

int	ft_digittoint(int c)
{
	if (ft_isdigit(c))
	{
		return (c - '0');
	}
	c |= 0x20;
	if (c >= 'a' && c <= 'f')
	{
		return (c - 'a' + 10);
	}
	return (0);
}
